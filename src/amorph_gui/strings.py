def run_button_text(n):
    """
    The text of the run button for n runs, with the Russian plural.
    """
    if n % 10 == 1 and n % 100 != 11:
        form = RUN_FORMS[0]
    elif 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        form = RUN_FORMS[1]
    else:
        form = RUN_FORMS[2]
    return form.format(n)


